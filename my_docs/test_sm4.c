// 辅助函数
static inline uint32_t rotl32(uint32_t x, unsigned int n) {
    return (x << n) | (x >> (32 - n));
}

static inline uint32_t bytes_to_uint32(const uint8_t* bytes) {
    return ((uint32_t)bytes[0] << 24) | ((uint32_t)bytes[1] << 16) |
           ((uint32_t)bytes[2] << 8) | ((uint32_t)bytes[3]);
}

static inline void uint32_to_bytes(uint32_t val, uint8_t* bytes) {
    bytes[0] = (val >> 24) & 0xFF;
    bytes[1] = (val >> 16) & 0xFF;
    bytes[2] = (val >> 8) & 0xFF;
    bytes[3] = val & 0xFF;
}

// SM4 S-box 查找
uint8_t sm4_sbox(uint8_t in) {
    return SM4_SBOX[in];
}

// 合成置换 τ
uint32_t sm4_tau(uint32_t a) {
    uint8_t bytes[4];
    uint32_to_bytes(a, bytes);

    bytes[0] = sm4_sbox(bytes[0]);
    bytes[1] = sm4_sbox(bytes[1]);
    bytes[2] = sm4_sbox(bytes[2]);
    bytes[3] = sm4_sbox(bytes[3]);

    return bytes_to_uint32(bytes);
}

// 线性变换 L (用于加密)
uint32_t sm4_linear_l(uint32_t b) {
    return b ^ rotl32(b, 2) ^ rotl32(b, 10) ^ rotl32(b, 18) ^ rotl32(b, 24);
}

// 线性变换 L' (用于密钥扩展)
uint32_t sm4_linear_l_prime(uint32_t b) {
    return b ^ rotl32(b, 13) ^ rotl32(b, 23);
}

// T 变换 (加密用)
static inline uint32_t sm4_t(uint32_t x) {
    return sm4_linear_l(sm4_tau(x));
}

// T' 变换 (密钥扩展用)
static inline uint32_t sm4_t_prime(uint32_t x) {
    return sm4_linear_l_prime(sm4_tau(x));
}

// SM4 轮密钥结构
typedef struct {
    uint32_t round_keys[32];
} sm4_round_keys_t;

// 密钥扩展算法 (加密密钥)
void sm4_init_round_keys(sm4_round_keys_t* rk, const uint8_t* key) {
    uint32_t K[36]; // K[0..3] 中间密钥, K[4..35] = rk[0..31]

    // MK 转换为 K[0..3]
    for (int i = 0; i < 4; i++) {
        K[i] = bytes_to_uint32(key + 4 * i) ^ FK[i];
    }

    // 生成32轮轮密钥
    for (int i = 0; i < 32; i++) {
        K[i + 4] = K[i] ^ sm4_t_prime(K[i + 1] ^ K[i + 2] ^ K[i + 3] ^ CK[i]);
        rk->round_keys[i] = K[i + 4];
    }
}

// 生成解密轮密钥 (逆序)
void sm4_init_decrypt_keys(sm4_round_keys_t* rk, const uint8_t* key) {
    sm4_round_keys_t encrypt_keys;
    sm4_init_round_keys(&encrypt_keys, key);

    // 解密轮密钥是加密轮密钥的逆序
    for (int i = 0; i < 32; i++) {
        rk->round_keys[i] = encrypt_keys.round_keys[31 - i];
    }
}

// SM4 加密算法
void sm4_encrypt_block(const sm4_round_keys_t* rk, const uint8_t* plaintext,
                       uint8_t* ciphertext) {
    uint32_t X[36]; // X[0..3] 输入, X[4..35] 中间状态

    // 加载明文
    for (int i = 0; i < 4; i++) {
        X[i] = bytes_to_uint32(plaintext + 4 * i);
    }

    // 32轮迭代: X[i+4] = X[i] ⊕ T(X[i+1] ⊕ X[i+2] ⊕ X[i+3] ⊕ rk[i])
    for (int i = 0; i < 32; i++) {
        X[i + 4] = X[i] ^ sm4_t(X[i + 1] ^ X[i + 2] ^ X[i + 3] ^ rk->round_keys[i]);
    }

    // 反序变换输出: (X[35], X[34], X[33], X[32])
    for (int i = 0; i < 4; i++) {
        uint32_to_bytes(X[35 - i], ciphertext + 4 * i);
    }
}

// 打印十六进制数据
void print_hex(const char* label, const uint8_t* data, size_t len) {
    printf("%s: ", label);
    for (size_t i = 0; i < len; i++) {
        printf("%02x", data[i]);
    }
    printf("\n");
}

int main() {
    // 测试向量来自 GM/T 0002-2012 附录A
    const uint8_t key[16] = {
        0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
        0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10
    };

    const uint8_t plaintext[16] = {
        0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef,
        0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10
    };

    // 预期密文 (来自标准)
    const uint8_t expected_ciphertext[16] = {
        0x68, 0x1e, 0xdf, 0x34, 0xd2, 0x06, 0x96, 0x5e,
        0x86, 0xb3, 0xe9, 0x4f, 0x53, 0x6e, 0x42, 0x46
    };

    uint8_t ciphertext[16];
    uint8_t decrypted[16];

    printf("SM4 加密测试\n");
    printf("============\n");

    print_hex("密钥", key, 16);
    print_hex("明文", plaintext, 16);
    print_hex("预期密文", expected_ciphertext, 16);

    // 初始化轮密钥
    sm4_round_keys_t encrypt_keys, decrypt_keys;
    sm4_init_round_keys(&encrypt_keys, key);
    sm4_init_decrypt_keys(&decrypt_keys, key);

    // 加密
    sm4_encrypt_block(&encrypt_keys, plaintext, ciphertext);
    print_hex("实际密文", ciphertext, 16);

    // 验证加密结果
    if (memcmp(ciphertext, expected_ciphertext, 16) == 0) {
        printf("✅ 加密测试通过！\n");
    } else {
        printf("❌ 加密测试失败！\n");
        return 1;
    }

    // 解密测试 (使用解密密钥)
    sm4_encrypt_block(&decrypt_keys, ciphertext, decrypted);
    print_hex("解密结果", decrypted, 16);

    if (memcmp(decrypted, plaintext, 16) == 0) {
        printf("✅ 解密测试通过！\n");
    } else {
        printf("❌ 解密测试失败！\n");
        return 1;
    }

    printf("\n测试完成！SM4实现正确。\n");
    return 0;
}