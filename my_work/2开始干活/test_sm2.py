    def __init__(self):
        self.rk = [] # Round Keys

    # Helper: Circular Left Shift [cite: 50]
    def _rotl(self, x, n):
        return ((x << n) & 0xffffffff) | ((x >> (32 - n)) & 0xffffffff)

    # Helper: Non-linear transform (Tau) - S-box lookup [cite: 67]
    def _tau(self, a):
        b0 = self.SBOX[(a >> 24) & 0xff]
        b1 = self.SBOX[(a >> 16) & 0xff]
        b2 = self.SBOX[(a >> 8) & 0xff]
        b3 = self.SBOX[a & 0xff]
        return (b0 << 24) | (b1 << 16) | (b2 << 8) | b3

    # Helper: Linear Transform L (Encryption) 
    def _L(self, b):
        return b ^ self._rotl(b, 2) ^ self._rotl(b, 10) ^ self._rotl(b, 18) ^ self._rotl(b, 24)

    # Helper: Linear Transform L' (Key Expansion) [cite: 92]
    def _L_prime(self, b):
        return b ^ self._rotl(b, 13) ^ self._rotl(b, 23)

    # Helper: Mixer T (Tau + L) [cite: 64]
    def _T(self, x):
        return self._L(self._tau(x))

    # Helper: Mixer T' (Tau + L') for Key Expansion [cite: 89, 91]
    def _T_prime(self, x):
        return self._L_prime(self._tau(x))

    # 7.3 Key Expansion Algorithm [cite: 87, 88, 89]
    def expand_key(self, mk_bytes):
        # Convert 128-bit key to 4 words
        mk = list(struct.unpack('>4I', mk_bytes))
        k = [0] * 36
        
        # Initialization
        k[0] = mk[0] ^ self.FK[0]
        k[1] = mk[1] ^ self.FK[1]
        k[2] = mk[2] ^ self.FK[2]
        k[3] = mk[3] ^ self.FK[3]
        
        self.rk = []
        for i in range(32):
            # rk_i = K_{i+4}
            rk_val = k[i] ^ self._T_prime(k[i+1] ^ k[i+2] ^ k[i+3] ^ self.CK[i])
            k[i+4] = rk_val
            self.rk.append(rk_val)

    # 7.1 Encryption Algorithm [cite: 79, 81, 82]
    def crypt_ecb(self, input_bytes, mode='encrypt'):
        # Convert 128-bit block to 4 words
        X = list(struct.unpack('>4I', input_bytes))
        
        # Determine round keys based on mode 
        round_keys = self.rk if mode == 'encrypt' else self.rk[::-1]
        
        # 32 Rounds of iteration
        for i in range(32):
            # F function: X_{i+4} = X_i ^ T(X_{i+1} ^ X_{i+2} ^ X_{i+3} ^ rk_i)
            tmp = X[0] ^ self._T(X[1] ^ X[2] ^ X[3] ^ round_keys[i])
            # Slide window: X0, X1, X2, X3 <- X1, X2, X3, tmp
            X[0], X[1], X[2], X[3] = X[1], X[2], X[3], tmp
            
        # Reverse Transform R 
        # Output is (X35, X34, X33, X32) which corresponds to current (X3, X2, X1, X0) in our sliding window
        return struct.pack('>4I', X[3], X[2], X[1], X[0])

